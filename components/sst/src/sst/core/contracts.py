"""Formal schema contracts for SST task packets, candidate proposals, scores, and human decisions."""

from __future__ import annotations

import hashlib
import json
from datetime import UTC, datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from sst.core.models import DeterministicGateResult


class TaskPacket(BaseModel):
    """Immutable, frozen task packet compiled before any worker or model invocation."""

    model_config = ConfigDict(frozen=True)

    task_id: str
    goal: str
    source_repo_root: str
    base_commit: str
    snapshot_hash: str
    allowed_paths: list[str] = Field(default_factory=list)
    forbidden_paths: list[str] = Field(default_factory=list)
    invariants: list[str] = Field(default_factory=list)
    interfaces: list[str] = Field(default_factory=list)
    acceptance_commands: list[str] = Field(default_factory=list)
    evidence_references: dict[str, str] = Field(default_factory=dict)
    # None (default) means the caller sets no bound and the engine policy governs.
    time_budget_seconds: int | None = None
    token_budget: int | None = None
    cost_budget_usd: float | None = None
    prompt_template_hash: str = ""
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    def compute_hash(self) -> str:
        """Computes deterministic digest over all immutable packet fields."""
        payload = {
            "task_id": self.task_id,
            "goal": self.goal,
            "source_repo_root": self.source_repo_root,
            "base_commit": self.base_commit,
            "snapshot_hash": self.snapshot_hash,
            "allowed_paths": sorted(self.allowed_paths),
            "forbidden_paths": sorted(self.forbidden_paths),
            "invariants": sorted(self.invariants),
            "interfaces": sorted(self.interfaces),
            "acceptance_commands": self.acceptance_commands,
            "evidence_references": sorted(self.evidence_references.items()),
            "time_budget_seconds": self.time_budget_seconds,
            "token_budget": self.token_budget,
            "cost_budget_usd": self.cost_budget_usd,
            "prompt_template_hash": self.prompt_template_hash,
        }
        return hashlib.sha256(json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()


class CandidateProposal(BaseModel):
    """Schema-validated patch proposal generated by a worker or model."""

    model_config = ConfigDict(frozen=True)

    candidate_id: str
    tree_id: str
    parent_ids: list[str] = Field(default_factory=list)
    role: str = "DIVERGE"  # DIVERGE, REFINE, CRITIQUE, SYNTHESIZE
    title: str
    rationale: str
    target_paths: list[str] = Field(default_factory=list)
    patch_diff: str = ""
    file_operations: list[dict[str, Any]] = Field(default_factory=list)
    model_id: str = ""
    prompt_hash: str = ""
    metadata: dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @property
    def primary_parent_id(self) -> str | None:
        return self.parent_ids[0] if self.parent_ids else None


class ScoreBreakdown(BaseModel):
    """Component score breakdown distinguishing hard gates from soft ranking."""

    model_config = ConfigDict(frozen=True)

    passed_hard_gates: bool = False
    hard_gates: dict[str, bool] = Field(default_factory=dict)
    # E.g. {"syntax": True, "lint": True, "tests": True, "scope": True, "secret_scan": True}
    soft_scores: dict[str, float] = Field(default_factory=dict)
    # E.g. {"value_score": 0.92, "architectural_fit": 0.95, "coverage_delta": 0.05}
    normalized_reward: float = Field(default=0.0, ge=0.0, le=1.0)
    raw_metrics: dict[str, Any] = Field(default_factory=dict)
    critic_verdict: str | None = None  # APPROVE, PRUNE, SYNTHESIZE, ESCALATE_HUMAN
    critic_rationale: str | None = None
    evaluated_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class HumanDecisionRecord(BaseModel):
    """Cryptographically auditable record of an explicit human decision."""

    model_config = ConfigDict(frozen=True)

    decision_id: str
    tree_id: str
    node_id: str
    reason: str
    verdict: str  # APPROVED, REJECTED, REVISED
    approver: str = "operator"
    notes: str | None = None
    recorded_at: datetime = Field(default_factory=lambda: datetime.now(UTC))

    def compute_hash(self) -> str:
        """Computes deterministic digest over immutable decision fields."""
        payload = {
            "decision_id": self.decision_id,
            "tree_id": self.tree_id,
            "node_id": self.node_id,
            "reason": self.reason,
            "verdict": self.verdict,
            "approver": self.approver,
            "notes": self.notes or "",
        }
        return hashlib.sha256(json.dumps(payload, sort_keys=True).encode("utf-8")).hexdigest()


class TerminationReason(StrEnum):
    """Why a bounded search run stopped (terminal outcome of run_search)."""

    CHAMPION_FOUND = "champion_found"
    NO_CANDIDATE = "no_candidate"
    BUDGET_EXHAUSTED = "budget_exhausted"
    CANCELLED = "cancelled"


class ProviderErrorRecord(BaseModel):
    """Frozen record of one failed model-provider invocation during search."""

    model_config = ConfigDict(frozen=True)

    role: str  # diverge | refine | synthesize | critique
    category: str  # gateway error category (e.g. unreachable_endpoint, rate_limit)
    remediation: str  # human-actionable remediation from the gateway error hierarchy
    message: str  # redacted error message (never contains raw secrets)
    profile: str | None = None
    iteration: int | None = None


class BudgetConsumed(BaseModel):
    """Frozen snapshot of resources consumed by one search run."""

    model_config = ConfigDict(frozen=True)

    tokens_consumed: int = 0
    estimated_cost_usd: float = 0.0
    elapsed_seconds: float = 0.0
    iterations_completed: int = 0


class AlternativeCandidate(BaseModel):
    """One evaluated candidate with its score, verifier outcome, and evidence refs."""

    model_config = ConfigDict(frozen=True)

    candidate: CandidateProposal
    score: ScoreBreakdown | None = None  # None when pruned before critique (verifier failed)
    verifier_outcome: DeterministicGateResult | None = None
    evidence_refs: list[str] = Field(default_factory=list)  # event_ids for this candidate


class GatewayBinding(BaseModel):
    """Frozen record of one role/profile/model wiring used by a search run.

    ``kind`` is the provider-kind enum NAME (e.g. "TEST", "OLLAMA",
    "OPENAI_COMPATIBLE") so fixture/test providers are unmistakable in the
    envelope. ``role`` is "*" for profiles with no role route.
    """

    model_config = ConfigDict(frozen=True)

    role: str
    profile: str
    model: str
    kind: str


class SearchResult(BaseModel):
    """Frozen typed envelope returned by SSTSearchController.run_search."""

    model_config = ConfigDict(frozen=True)

    tree_id: str
    termination_reason: TerminationReason
    champion: CandidateProposal | None = None
    alternatives: list[AlternativeCandidate] = Field(default_factory=list)
    budget_consumed: BudgetConsumed = Field(default_factory=BudgetConsumed)
    provider_errors: list[ProviderErrorRecord] = Field(default_factory=list)
    gateway_bindings: list[GatewayBinding] = Field(default_factory=list)
    event_log_ref: str = ""
