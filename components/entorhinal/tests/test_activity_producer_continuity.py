"""Producer-generated continuity: lecture/code/lecture through real producers.

Every event shape in this file is generated by the actual producer code —
``browser_media`` builders (extension-faithful ``browser-extension``
clock-domain shapes) and ``EditorMetadataSender`` / ``editor_focus``
builders — never hand-authored dicts. The main scenario additionally
travels the real transport path (sender POST -> ``LocalActivityReceiver``
-> inbox file -> ``ActivityService``), so receipts, grant checks,
idempotency, and session derivation are all exercised end to end.

Segmentation edge cases (pause carve-out, different lecture, unknown
identity, blur plane, heartbeats, seek) ingest producer-built shapes
directly into ``ActivityService`` to isolate core segmentation behavior
from transport; the shapes remain producer-generated, not fixtures.

All inputs are NEW synthetic data on ``.example.test`` hosts and
``/synth`` paths. No live browser/editor, no user stores, no network
beyond loopback, no remote classification.
"""

