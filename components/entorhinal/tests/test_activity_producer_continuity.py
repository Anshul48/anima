def test_producer_consent_denial_and_revocation(tmp_path: Path) -> None:
    """Host denial is client-side; grant denial/revocation is attributable."""
    with _live_transport(tmp_path) as (browser, editor, inbox, grants, _receiver):
        # Consent/host denial: unallowlisted host never leaves the producer.
        dropped = browser.send_navigation(
            "deny-nav-1", "https://other.example.test/page", "SYNTH other",
            observed_at=T0)
        assert dropped.admitted is False
        assert dropped.status == "dropped"
        assert dropped.reason == "suppressed:domain-not-allowlisted"
        assert "deny-nav-1:suppressed:domain-not-allowlisted" in browser.dropped

        dropped_media = browser.send_media_state(
            "deny-media-1", "https://other.example.test/watch?v=X",
            "SYNTH other", "other.example.test|v=X", 5.0, 100.0,
            "playing", observed_at=T0)
        assert dropped_media.admitted is False
        assert dropped_media.reason == "suppressed:domain-not-allowlisted"

        outside = editor.send_focus(
            "deny-ed-1", "/elsewhere/notes.py", "notes",
            observed_at=T0)
        assert outside.admitted is False
        assert outside.reason == "suppressed:outside-workspace"

        # Unknown grant: server-side denial, nothing written.
        denied = browser._post(_media_event(
            "deny-grant-1", ActivityKind.MEDIA_FOREGROUND, T0,
            _media_payload(0.0, "playing"), grant_id="grant-unknown", seq=9))
        assert denied.admitted is False
        assert denied.reason == "denied:unknown-grant:grant-unknown"

        # One good event is admitted, then the grant is revoked mid-run.
        _require_admitted(browser._post(_media_event(
            "deny-ok-1", ActivityKind.MEDIA_FOREGROUND, T0,
            _media_payload(0.0, "playing"), seq=10)))
        assert grants.revoke(GRANT_BROWSER, "synthetic user revoke") is True
        revoked = browser._post(_media_event(
            "deny-ok-2", ActivityKind.MEDIA_FOREGROUND,
            T0 + timedelta(minutes=1),
            _media_payload(60.0, "playing"), seq=11))
        assert revoked.admitted is False
        assert revoked.reason == f"denied:grant-revoked:{GRANT_BROWSER}"

        # Exactly the one pre-revocation event reached the inbox; the
        # editor grant (unrevoked) still admits.
        _require_admitted(editor.send_focus(
            "deny-ed-2", EDITOR_FILE, EDITOR_WORKSPACE,
            language_id="python", observed_at=T0 + timedelta(minutes=1)))
        lines = inbox.read_text(encoding="utf-8").strip().splitlines()
        assert len(lines) == 2
        assert {json.loads(line)["event_id"] for line in lines} == {
            "deny-ok-1", "deny-ed-2"}


def test_producer_offline_retry_and_stable_duplicates(tmp_path: Path) -> None:
    """Offline POSTs fail loudly; same-event_id retries collapse exactly."""
    inbox = tmp_path / "retry-inbox.jsonl"
    grants = _grants()
    receiver = LocalActivityReceiver(
        token=TOKEN, grants=grants, sink=InboxFileSink(inbox))
    receiver.start()
    try:
        with BrowserMetadataSender(
            receiver_url=receiver.url, token=TOKEN,
            grant_id=GRANT_BROWSER, allow_domains=[LECTURE_HOST],
            enabled=True,
        ) as browser:
            first = _media_event(
                "retry-1", ActivityKind.MEDIA_FOREGROUND, T0,
                _media_payload(0.0, "playing"), seq=1)
            _require_admitted(browser._post(first))

            # Offline: the receiver is gone; the failure is a receipt,
            # never a silent drop.
            receiver.stop()
            offline_event = _media_event(
                "retry-2", ActivityKind.MEDIA_FOREGROUND,
                T0 + timedelta(minutes=1),
                _media_payload(60.0, "playing"), seq=2)
            offline = browser._post(offline_event)
            assert offline.admitted is False
            assert offline.status == "transport-error"
    finally:
        try:
            receiver.stop()
        except Exception:
            pass

    # Receiver restarts (new ephemeral port, same inbox/grants/token):
    # the retry reuses the same event_id and is admitted once.
    receiver2 = LocalActivityReceiver(
        token=TOKEN, grants=grants, sink=InboxFileSink(inbox))
    receiver2.start()
    try:
        with BrowserMetadataSender(
            receiver_url=receiver2.url, token=TOKEN,
            grant_id=GRANT_BROWSER, allow_domains=[LECTURE_HOST],
            enabled=True,
        ) as browser2:
            retry = _media_event(
                "retry-2", ActivityKind.MEDIA_FOREGROUND,
                T0 + timedelta(minutes=1),
                _media_payload(60.0, "playing"), seq=2)
            assert retry.content_hash() == offline_event.content_hash()
            _require_admitted(browser2._post(retry))
    finally:
        receiver2.stop()

    service = ActivityService(grants=grants)
    outcomes = _ingest_inbox(inbox, service)
    assert [o.status for o in outcomes] == ["admitted", "admitted"]

    # Stable duplicate identities: exact retry -> duplicate (original kept);
    # same key with changed content -> conflict (never merged).
    again = service.ingest(
        ActivityEvent.model_validate_json(
            inbox.read_text(encoding="utf-8").strip().splitlines()[0]))
    assert again.status == "duplicate"
    changed = _media_event(
        "retry-1", ActivityKind.MEDIA_FOREGROUND, T0,
        _media_payload(999.0, "playing"), seq=1)
    conflict = service.ingest(changed)
    assert conflict.status == "conflict"

    # The stored event is the original, and derived ids are stable.
    stored = service.events()
    assert len(stored) == 2
    assert stored[0].payload["media_position_s"] == 0.0
    service.rebuild()
    assert len(service.spans()) == 1
    assert len(service.sessions()) == 1


