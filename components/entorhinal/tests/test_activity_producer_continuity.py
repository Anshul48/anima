# -- producer-shape builders (the actual producer code paths) --------------


def _media_payload(
    position: Optional[float],
    state: str,
    media_id: Optional[str] = LECTURE_MEDIA_ID,
    host: Optional[str] = LECTURE_HOST,
    heartbeat_seq: Optional[int] = None,
) -> Dict[str, Any]:
    return build_media_payload(
        media_id=media_id, media_host=host, media_state=state,
        position_s=position, duration_s=LECTURE_DURATION,
        media_title=LECTURE_TITLE, media_element="video",
        muted=False, playback_rate=1.0, audible=True, page_visible=True,
        heartbeat_seq=heartbeat_seq,
    )


def _media_event(
    event_id: str,
    kind: ActivityKind,
    observed_at: datetime,
    payload: Dict[str, Any],
    uri: str = LECTURE_URI,
    title: Optional[str] = LECTURE_TITLE,
    foreground: bool = True,
    grant_id: str = GRANT_BROWSER,
    seq: Optional[int] = None,
) -> ActivityEvent:
    blob = build_producer_event_dict(
        event_id=event_id, kind=kind, observed_at=observed_at,
        uri=uri, window_title=title, payload=payload,
        foreground=foreground, grant_id=grant_id, source_seq=seq,
        synthetic=True, redaction_labels=["synthetic-fixture"],
    )
    return ActivityEvent.model_validate(blob)


def _editor_event(
    event_id: str,
    kind: ActivityKind,
    observed_at: datetime,
    abs_path: str = EDITOR_FILE,
    workspace: str = EDITOR_WORKSPACE,
    language: str = "python",
    foreground: bool = True,
    edit_events: Optional[int] = None,
    grant_id: str = GRANT_EDITOR,
    seq: Optional[int] = None,
) -> ActivityEvent:
    rel = abs_path[len(EDITOR_ROOT) + 1:]
    payload = build_editor_payload(
        workspace_name=workspace, file_rel=rel,
        language_id=language, edit_events=edit_events,
    )
    blob = build_editor_event_dict(
        event_id=event_id, kind=kind, observed_at=observed_at,
        uri=file_uri_for(abs_path),
        window_title=f"{rel} — {workspace}", payload=payload,
        foreground=foreground, grant_id=grant_id, source_seq=seq,
        synthetic=True, redaction_labels=["synthetic-fixture"],
    )
    return ActivityEvent.model_validate(blob)


@contextmanager
def _live_transport(tmp_path: Path) -> Iterator[Tuple[
    BrowserMetadataSender, EditorMetadataSender, Path, GrantStore,
    LocalActivityReceiver,
]]:
    """Real sender -> receiver -> inbox path on loopback (synthetic only)."""
    inbox = tmp_path / "continuity-inbox.jsonl"
    grants = _grants()
    receiver = LocalActivityReceiver(
        token=TOKEN, grants=grants, sink=InboxFileSink(inbox),
    )
    receiver.start()
    try:
        with BrowserMetadataSender(
            receiver_url=receiver.url, token=TOKEN,
            grant_id=GRANT_BROWSER, allow_domains=[LECTURE_HOST],
            enabled=True,
        ) as browser, EditorMetadataSender(
            receiver_url=receiver.url, token=TOKEN,
            grant_id=GRANT_EDITOR, allowed_roots=[EDITOR_ROOT],
            enabled=True,
        ) as editor:
            yield browser, editor, inbox, grants, receiver
    finally:
        receiver.stop()


def _ingest_inbox(inbox: Path, service: ActivityService) -> List[Any]:
    outcomes = []
    for line in inbox.read_text(encoding="utf-8").strip().splitlines():
        outcomes.append(service.ingest(ActivityEvent.model_validate_json(line)))
    return outcomes


def _require_admitted(receipt: ReceiverReceipt) -> ReceiverReceipt:
    assert receipt.admitted is True, receipt
    assert receipt.status == "admitted", receipt
    return receipt


def _label_for(labels: Any, session_id: str) -> Any:
    matches = [
        label for label in labels
        if label.target_kind == "session" and label.target_id == session_id
    ]
    assert len(matches) == 1, [label.target_id for label in labels]
    return matches[0]


# -- required case: lecture 30m -> code 5m -> same lecture ------------------


def test_producer_lecture_code_lecture_two_sessions_three_spans(tmp_path: Path) -> None:
    """Producer-built shapes through real transport: 2 sessions / 3 spans."""
    with _live_transport(tmp_path) as (browser, editor, inbox, grants, _receiver):
        seq = 0

        def post_media(event_id: str, kind: ActivityKind, at: datetime,
                       payload: Dict[str, Any]) -> None:
            nonlocal seq
            seq += 1
            _require_admitted(browser._post(
                _media_event(event_id, kind, at, payload, seq=seq)))

        # Lecture segment 1: 30 minutes of producer media heartbeats.
        post_media("cont-l1", ActivityKind.MEDIA_FOREGROUND, T0,
                   _media_payload(0.0, "playing", heartbeat_seq=1))
        post_media("cont-l2", ActivityKind.MEDIA_FOREGROUND,
                   T0 + timedelta(minutes=10),
                   _media_payload(600.0, "playing", heartbeat_seq=2))
        post_media("cont-l3", ActivityKind.MEDIA_FOREGROUND,
                   T0 + timedelta(minutes=20),
                   _media_payload(1200.0, "playing", heartbeat_seq=3))
        pause_payload = build_media_marker_payload(
            marker="pause", base=_media_payload(1800.0, "paused"))
        post_media("cont-l-pause", ActivityKind.MEDIA_MARKER,
                   T0 + timedelta(minutes=30), pause_payload)

        # Coding interruption: 5 minutes of editor focus observations.
        _require_admitted(editor.send_focus(
            "cont-c1", EDITOR_FILE, EDITOR_WORKSPACE,
            language_id="python", observed_at=T0 + timedelta(minutes=31)))
        _require_admitted(editor.send_focus(
            "cont-c2", EDITOR_FILE, EDITOR_WORKSPACE,
            language_id="python",
            observed_at=T0 + timedelta(minutes=33, seconds=30)))
        _require_admitted(editor.send_focus(
            "cont-c3", EDITOR_FILE, EDITOR_WORKSPACE,
            language_id="python", observed_at=T0 + timedelta(minutes=36)))

        # Same lecture resumes where it paused (position continuity).
        resume_payload = build_media_marker_payload(
            marker="resume", base=_media_payload(1800.0, "playing"))
        post_media("cont-l-resume", ActivityKind.MEDIA_MARKER,
                   T0 + timedelta(minutes=36), resume_payload)
        post_media("cont-l4", ActivityKind.MEDIA_FOREGROUND,
                   T0 + timedelta(minutes=40),
                   _media_payload(2040.0, "playing", heartbeat_seq=4))
        post_media("cont-l5", ActivityKind.MEDIA_FOREGROUND,
                   T0 + timedelta(minutes=50),
                   _media_payload(2640.0, "playing", heartbeat_seq=5))

        service = ActivityService(grants=grants)
        outcomes = _ingest_inbox(inbox, service)
        assert [o.status for o in outcomes] == ["admitted"] * 10
        service.rebuild()

        spans = service.spans()
        sessions = service.sessions()
        assert len(spans) == 3, [s.span_id for s in spans]
        assert all(s.background is False for s in spans)
        assert len(sessions) == 2, [s.session_id for s in sessions]

        lecture = next(
            s for s in sessions
            if s.content_identity and LECTURE_MEDIA_ID in s.content_identity.key)
        code = next(
            s for s in sessions
            if s.content_identity and s.content_identity.kind == "code")
        assert len(lecture.span_ids) == 2
        assert len(code.span_ids) == 1

        # Resumption links on content identity + position continuity +
        # title corroboration (0.45 + 0.15 = 0.60): no gap-only inference.
        assert len(lecture.resumption_links) == 1
        link = lecture.resumption_links[0]
        assert link.evidence == ["position-continuity", "title-fingerprint-match"]
        assert link.confidence == 0.60

        # Active time: capped 120s steps within each span; the 5-minute
        # coding interval is never charged to the lecture.
        assert lecture.total_elapsed_seconds == 1800.0 + 840.0
        assert lecture.total_active_seconds == 600.0
        assert code.total_elapsed_seconds == 300.0
        assert code.total_active_seconds == 240.0

        # Provenance: pause/resume markers recorded on their spans.
        first_span = next(s for s in spans if "cont-l1" in s.event_ids)
        resumed_span = next(s for s in spans if "cont-l-resume" in s.event_ids)
        assert "cont-l-pause" in first_span.provenance.marker_event_ids
        assert "cont-l-resume" in resumed_span.provenance.marker_event_ids
        assert first_span.last_position_s == 1800.0
        assert resumed_span.first_position_s == 1800.0

        # Local classification of producer-generated sessions (no remote call).
        labels = service.labels()
        assert _label_for(labels, lecture.session_id).activity == "lecture-viewing"
        assert _label_for(labels, code.session_id).activity == "coding"

        # Stable identities: rebuild from the same admitted events.
        before = sorted(s.session_id for s in sessions)
        service.rebuild()
        assert sorted(s.session_id for s in service.sessions()) == before


def test_producer_pause_midspan_carves_active_time() -> None:
    """A pause/resume pair inside one span excludes paused time (provenance)."""
    events = [
        _media_event("carve-play", ActivityKind.MEDIA_FOREGROUND, T0,
                     _media_payload(0.0, "playing"), seq=1),
        _media_event("carve-pause", ActivityKind.MEDIA_MARKER,
                     T0 + timedelta(minutes=5), build_media_marker_payload(
                         marker="pause", base=_media_payload(300.0, "paused")),
                     seq=2),
        _media_event("carve-resume", ActivityKind.MEDIA_MARKER,
                     T0 + timedelta(minutes=8), build_media_marker_payload(
                         marker="resume", base=_media_payload(300.0, "playing")),
                     seq=3),
        _media_event("carve-play2", ActivityKind.MEDIA_FOREGROUND,
                     T0 + timedelta(minutes=10),
                     _media_payload(420.0, "playing"), seq=4),
    ]
    service = ActivityService(grants=_grants())
    assert [o.status for o in service.ingest_many(events)] == ["admitted"] * 4
    service.rebuild()
    assert len(service.spans()) == 1
    span = service.spans()[0]
    # Capped steps 120+120+120=360 minus the 180s pause interval.
    assert span.active_seconds == 180.0
    assert span.provenance.pause_intervals_s == [(300.0, 480.0)]
    assert span.provenance.marker_event_ids == ["carve-pause", "carve-resume"]


def test_producer_focus_loss_background_not_charged() -> None:
    """Window blur lands on the background plane; foreground stays honest."""
    events = [
        _media_event("blur-l1", ActivityKind.MEDIA_FOREGROUND, T0,
                     _media_payload(0.0, "playing"), seq=1),
        _media_event("blur-evt", ActivityKind.WINDOW_BACKGROUND,
                     T0 + timedelta(minutes=5),
                     {"transition": "window-blurred"},
                     foreground=False, seq=2),
        _media_event("blur-l2", ActivityKind.MEDIA_FOREGROUND,
                     T0 + timedelta(minutes=10),
                     _media_payload(600.0, "playing"), seq=3),
    ]
    service = ActivityService(grants=_grants())
    assert [o.status for o in service.ingest_many(events)] == ["admitted"] * 3
    service.rebuild()
    spans = service.spans()
    assert len(spans) == 2
    foreground = next(s for s in spans if s.background is False)
    background = next(s for s in spans if s.background is True)
    assert background.event_ids == ["blur-evt"]
    # The blur is a boundary signal, not content: it never joins the
    # lecture session and never charges foreground active time.
    assert foreground.active_seconds == 120.0
    assert len(service.sessions()) == 2
    lecture = next(
        s for s in service.sessions()
        if s.content_identity and LECTURE_MEDIA_ID in s.content_identity.key)
    assert lecture.span_ids == [foreground.span_id]


